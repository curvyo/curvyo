const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--enable-unsafe-webgpu','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const visibleFrame=async name=>{const box=await page.locator('[data-page-frames] > div').filter({hasText:name}).boundingBox();const canvas=await page.locator('canvas').first().boundingBox();assert(box && canvas && box.x+box.width>canvas.x && box.x<canvas.x+canvas.width && box.y+box.height>canvas.y && box.y<canvas.y+canvas.height,`${name} is not revealed`);};
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.CURVYO_BROWSER_URL || 'http://127.0.0.1:5173/',{waitUntil:'networkidle'});
 const grid=page.getByRole('grid',{name:'Pages',exact:true});
 await grid.waitFor();
 await page.getByRole('button',{name:'Add page',exact:true}).click();
 await page.waitForTimeout(200);
 assert.equal(await grid.getByRole('row').count(),2); await visibleFrame('Page 2');
 assert.equal(await grid.locator('[aria-current="true"]').innerText(),'Page 2\n210.0 × 297.0 mm');
 await grid.getByRole('button',{name:'Page 2',exact:true}).dblclick();
 const name=grid.getByRole('textbox',{name:'Name of Page 2'});
 await name.fill('Coaster 🦊'); await name.press('Enter');
 await grid.getByRole('button',{name:'Coaster 🦊',exact:true}).waitFor();
 // Document history must remain reachable from a focused page-row button.
 await grid.getByRole('button',{name:'Coaster 🦊',exact:true}).focus();
 await page.keyboard.press('Control+z');
 await grid.getByRole('button',{name:'Page 2',exact:true}).waitFor();
 await grid.getByRole('button',{name:'Page 2',exact:true}).focus();
 await page.keyboard.press('Control+Shift+z');
 await grid.getByRole('button',{name:'Coaster 🦊',exact:true}).waitFor();
 await grid.getByRole('button',{name:'Coaster 🦊',exact:true}).dblclick();
 const cancelName=grid.getByRole('textbox',{name:'Name of Coaster 🦊'});
 await cancelName.fill('Discard me'); await cancelName.press('Escape');
 assert.equal(await grid.getByRole('button',{name:'Discard me',exact:true}).count(),0);
 assert.equal(await grid.getByRole('button',{name:'Coaster 🦊',exact:true}).count(),1);
 const width=page.getByRole('textbox',{name:'Document width',exact:true});
 await width.fill('100'); await width.press('Enter');
 await page.waitForTimeout(150);
 assert.match(await grid.locator('[aria-current="true"]').innerText(),/100.0 × 297.0/);
 await grid.getByRole('button',{name:'Page 1',exact:true}).click();
 assert.equal(Number(await width.inputValue()),210); await visibleFrame('Page 1');
 await grid.getByRole('button',{name:'Coaster 🦊',exact:true}).click();
 await page.getByRole('button',{name:'Move page up',exact:true}).click();
 assert.match(await grid.getByRole('row').first().innerText(),/Coaster/);
 await grid.getByRole('button',{name:'Coaster 🦊',exact:true}).focus();
 await page.keyboard.press('Control+z');
 await grid.getByRole('row').first().getByRole('button',{name:'Page 1',exact:true}).waitFor();
 await grid.getByRole('button',{name:'Coaster 🦊',exact:true}).focus();
 await page.keyboard.press('Control+y');
 await grid.getByRole('row').first().getByRole('button',{name:'Coaster 🦊',exact:true}).waitFor();
 await page.getByRole('switch',{name:'Move frame only: Coaster 🦊',exact:true}).click();
 assert.equal(await page.getByRole('switch',{name:'Move frame only: Coaster 🦊',exact:true}).getAttribute('aria-checked'),'true');

 await page.getByRole('radio',{name:'cm, centimetres',exact:true}).click();
 const x=page.getByRole('spinbutton',{name:'Page X in cm',exact:true});
 const oldX=Number(await x.inputValue());
 await x.fill(String(oldX+1));await x.press('Enter');
 assert.equal(Number(await x.inputValue()),oldX+1);
 await page.getByRole('radio',{name:'mm, millimetres',exact:true}).click();
 assert(Math.abs(Number(await page.getByRole('spinbutton',{name:'Page X in mm',exact:true}).inputValue())-(oldX+1)*10)<0.001);
 const rowName=grid.getByRole('button',{name:'Coaster 🦊',exact:true});
 await rowName.focus();await rowName.press('F2');
 await grid.getByRole('textbox',{name:'Name of Coaster 🦊'}).fill('No rename');
 await grid.getByRole('textbox',{name:'Name of Coaster 🦊'}).press('Escape');
 await page.waitForFunction(()=>document.activeElement?.getAttribute('title')==='Coaster 🦊');
 assert.equal(await rowName.evaluate(el=>document.activeElement===el),true);
 const before=await grid.getByRole('row').allTextContents();
 const grip=await grid.getByRole('button',{name:'Reorder Coaster 🦊',exact:true}).boundingBox();
 const last=await grid.getByRole('row').last().boundingBox();
 await grid.getByRole('button',{name:'Reorder Coaster 🦊',exact:true}).focus();
 await page.mouse.move(grip.x+grip.width/2,grip.y+grip.height/2);await page.mouse.down();
 await page.mouse.move(last.x+last.width/2,last.y+last.height/2,{steps:5});
 await page.keyboard.press('Escape');await page.mouse.up();
 assert.deepEqual(await grid.getByRole('row').allTextContents(),before);
 await page.getByRole('button',{name:'Delete page: Coaster 🦊',exact:true}).click();
 assert.equal(await grid.getByRole('row').count(),1);
 assert.equal(await page.getByRole('button',{name:/^Delete page:/}).count(),0);
 assert.deepEqual(errors,[]);
 console.log('PASS browser: add, active row, rename/escape, active-only width, activation, keyboard-equivalent reorder, frame-only switch, delete/last-page protection; no page errors');
 await page.screenshot({path:'target/browser-check/pages.png'});
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
