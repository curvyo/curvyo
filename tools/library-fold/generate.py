#!/usr/bin/env python3
"""Generates the diacritic folding table of the library browser's search (ADR 0086 decision 3).

For every letter of Latin-1 Supplement, Latin Extended-A and -B (U+00C0 to U+024F) and Latin
Extended Additional (U+1E00 to U+1EFF): its lower case, decomposed (NFD) without combining marks,
when that is plain ASCII and differs from the letter; plus the letters decomposition leaves alone
(ss, ae, oe, o, l, d, th, d). Writes curvyo-library-core/src/fold_table.rs.

Python 3 standard library only (its `unicodedata`); run from anywhere:

    python3 -I tools/library-fold/generate.py
"""

import pathlib
import unicodedata

EXTRA = {"ß": "ss", "æ": "ae", "œ": "oe", "ø": "o", "ł": "l", "đ": "d", "þ": "th", "ð": "d"}
RANGES = [(0x00C0, 0x024F), (0x1E00, 0x1EFF)]
OUT = pathlib.Path(__file__).resolve().parents[2] / "curvyo-library-core" / "src" / "fold_table.rs"


def folded(ch: str) -> str | None:
    lower = ch.lower()
    if len(lower) != 1:
        return None
    if lower in EXTRA:
        return EXTRA[lower]
    base = "".join(c for c in unicodedata.normalize("NFD", lower) if not unicodedata.combining(c))
    if base != lower and base.isascii() and base.isalpha():
        return base
    return None


def main() -> None:
    table = {}
    for start, end in RANGES:
        for cp in range(start, end + 1):
            ch = chr(cp)
            if unicodedata.category(ch)[0] != "L":
                continue
            lower = ch.lower()
            if len(lower) == 1 and lower != ch:
                continue  # the upper-case letter is lowered first; its lower case is listed
            base = folded(ch)
            if base is not None:
                table[ch] = base
    lines = [
        "//! The Latin folding table of the library search (ADR 0086 decision 3), generated by",
        "//! `tools/library-fold/generate.py` from Python's `unicodedata` "
        f"(Unicode {unicodedata.unidata_version}); do not edit.",
        "",
        "/// `(lower-case letter, its folded text)`, sorted by the letter.",
        "pub(crate) const FOLDS: &[(char, &str)] = &[",
    ]
    for ch in sorted(table):
        lines.append(f"    ('\\u{{{ord(ch):04x}}}', \"{table[ch]}\"),")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(table)} letters -> {OUT}")


main()
