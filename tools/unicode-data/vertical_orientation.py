#!/usr/bin/env python3
"""Generates curvyo-text-core/src/vertical_orientation_data.rs from the Unicode Character
Database file VerticalOrientation.txt (UAX #50).

Usage: python3 -I tools/unicode-data/vertical_orientation.py VerticalOrientation.txt OUT.rs

The input is checked against the SHA-256 below, so the table is reproducible; a new Unicode
version updates SOURCE_URL and SOURCE_SHA256 together. Only the upright classes (U and Tu, whose
fallback is upright) are kept, merged into ranges; everything else is R or Tr (set sideways).
"""

import hashlib
import sys

SOURCE_URL = "https://www.unicode.org/Public/17.0.0/ucd/VerticalOrientation.txt"
SOURCE_SHA256 = "dcef09c3fb24d356b042569c328ec341efc5b53447700d799f2fb4834c3cd3cd"
UPRIGHT = {"U", "Tu"}


def upright_ranges(text):
    ranges = []
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        points, value = (field.strip() for field in line.split(";"))
        if value not in UPRIGHT:
            continue
        first, _, last = points.partition("..")
        start, end = int(first, 16), int(last or first, 16)
        if ranges and ranges[-1][1] + 1 == start:
            ranges[-1] = (ranges[-1][0], end)
        else:
            ranges.append((start, end))
    return ranges


def main():
    source, out = sys.argv[1], sys.argv[2]
    data = open(source, "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SOURCE_SHA256:
        sys.exit(f"{source}: SHA-256 {digest}, expected {SOURCE_SHA256}")
    ranges = upright_ranges(data.decode("utf-8"))
    rows = "\n".join(f"    (0x{a:04X}, 0x{b:04X})," for a, b in ranges)
    with open(out, "w", encoding="utf-8") as file:
        file.write(
            "//! Generated by `tools/unicode-data/vertical_orientation.py`; do not edit.\n"
            f"//! Source: <{SOURCE_URL}>, SHA-256 `{SOURCE_SHA256}`.\n"
            "#![allow(clippy::unreadable_literal)]\n\n"
            "/// The code point ranges whose `Vertical_Orientation` is U or Tu, sorted, disjoint.\n"
            f"pub(crate) const UPRIGHT: [(u32, u32); {len(ranges)}] = [\n{rows}\n];\n"
        )


if __name__ == "__main__":
    main()
